/**
 * Máscara tierra/océano de la cuadrícula de análisis (64 × 32 celdas; '#' = tierra, '.' = océano).
 *
 * Se obtuvo del MISMO video de la NASA, no de otra fuente: se tomó la mediana del fondo del mapa
 * en ~30 cuadros repartidos en todo el video (sin los píxeles amarillos de los rayos). El océano es un gris totalmente plano
 * (luminancia ≈ 19) y la tierra tiene relieve; se marcó como océano lo plano y de ese tono, y cada
 * celda toma el valor de la mayoría de sus píxeles. Las franjas polares (fuera del alcance del sensor)
 * quedan como "tierra", pero ahí no hay rayos. Las costas salen un poco engrosadas.
 */
